import streamlit as st
from dotenv import load_dotenv

from langchain_core.messages import HumanMessage, AIMessage
from langchain_chroma import Chroma

from src.utils_parsing import extract_local_sources, extract_steuerbuch_urls
from src.agent import get_agent_response_stream
from src.config import MAX_HISTORY_PAIRS

load_dotenv()


def start_agent(vector_store: Chroma) -> None:
    """
    Renders the main tax assistance chat interface and manages session state history.
    """
    st.title("Steuer-Assistenz")
    st.info(
        "Die Antworten stellen keine rechtsverbindliche Auskunft dar und können Fehler enthalten und kantonal variieren. "
        "Es wird keinerlei Haftung übernommen.",
        width="stretch"
    )

    if st.sidebar.button("Logout"):
        st.session_state.authenticated = False
        st.rerun()

    # Streamlit reruns the entire script from top to bottom on any user interaction.
    # We use st.session_state to persist data across these reactive reruns.
    if "messages" not in st.session_state:
        st.session_state.messages = []  # Raw text storage dictionary array for UI rendering
    if "chat_history" not in st.session_state:
        st.session_state.chat_history = []  # Structured LangChain Message objects for LLM context window

    # Repopulate historical chat messages into the UI container upon script rerun
    for message in st.session_state.messages:
        with st.chat_message(message["role"], avatar=message["avatar"]):
            st.markdown(message["content"])

    if prompt := st.chat_input("Wie kann ich helfen?", key="main_chat"):

        st.session_state.messages.append({"role": "user", "content": prompt, "avatar": '👤'})
        with st.chat_message("user", avatar='👤'):
            st.markdown(prompt)

        with st.chat_message("assistant", avatar='⚖️'):
            try:
                # The stream object yields tokens live as they are generated by the LLM
                stream, rag_context, collected_messages = get_agent_response_stream(
                    prompt,
                    vector_store,
                    st.session_state.chat_history
                )
                answer = st.write_stream(stream)

                # Context citation extraction
                local_sources = extract_local_sources(rag_context)
                steuerbuch_urls = extract_steuerbuch_urls(collected_messages)

                with st.expander("Quellen"):
                    if local_sources:
                        st.caption("**Lokale Quellen:**\n\n" + "\n\n".join(f"• {s}" for s in local_sources))
                    if steuerbuch_urls:
                        st.caption("**Steuerbuch-Quellen:**\n\n" + "\n\n".join(f"• {u}" for u in steuerbuch_urls))

            except ValueError as error:
                answer = str(error)
                st.markdown(answer)

        st.session_state.messages.append({"role": "assistant", "content": answer, "avatar": "⚖️"})
        st.session_state.chat_history.extend([
            HumanMessage(content=prompt),
            AIMessage(content=answer),
        ])

        # ROLLING WINDOW MEMORY MANAGEMENT: Prevents the prompt from growing infinitely.
        # This keeps API costs down and protects the model's token context boundary.
        st.session_state.chat_history = st.session_state.chat_history[-(MAX_HISTORY_PAIRS * 2):]


def start_authentication(vector_store: Chroma) -> None:
    """
    Renders the secure login form overlay and acts as a router to the main agent.
    """
    if "authenticated" not in st.session_state:
        st.session_state.authenticated = False

    # Guard Clause: Force login form display and block app entry if unauthorized
    if not st.session_state.authenticated:
        st.title("Login")
        username = st.text_input("Benutzername", type="default")
        password = st.text_input("Passwort", type="password")

        if st.button("Login"):
            if (username == st.secrets["credentials"]["username"] and
                    password == st.secrets["credentials"]["password"]):
                st.session_state.authenticated = True
                st.rerun()  # Instantly re-executes the file to route into start_agent()
            else:
                st.error("Falscher Benutzername oder Passwort")
        return

    # Fallback Execution Path: Route directly to workspace if session is verified
    start_agent(vector_store)